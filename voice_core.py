_overlay_atexit_done = False


def set_recording_state(active, phase="rec", started=None, limit_sec=None,
                        hint=None, note=None, level=None, quit_overlay=False,
                        ttl=None, fake=False):
    """
    Состояние для экранного индикатора. Отдельный процесс читает этот файл.

    Пишем через временный файл и os.replace: во время записи состояние обновляется
    десять раз в секунду, а индикатор читает тридцать. Обычная перезапись сначала
    усекает файл и только потом наполняет — в этот зазор читатель видит пустоту.
    os.replace на одном томе атомарен: читатель видит либо старый файл, либо новый.

    `expires_at` — срок годности состояния. Без него капсула висит на экране вечно,
    если писатель умер между «готово» и отложенным гашением (так и случилось 31.07):
    гасить было некому, а индикатор верил файлу бесконечно. Теперь состояние
    протухает само, и живучесть индикатора не зависит от того, как завершился писатель.

    Срок по умолчанию зависит от фазы: запись переписывается постоянно и живёт
    коротко, остальные фазы пишутся разово и ждут ответа сети (см. REC_TTL_SEC).

    `fake` — звук идёт из подставного файла, а не с микрофона. Капсула обязана
    выглядеть иначе: индикатор, который показывает запись там, где микрофон не
    открывался, обесценивает себя и в настоящем случае. Инцидент 2026-08-06:
    автотест с `--fake-mic` поднял на экране обычную красную капсулу, и со
    стороны это было неотличимо от того, что человека пишут.
    """
    if ttl is None:
        ttl = REC_TTL_SEC if phase == "rec" else STATE_TTL_SEC
    tmp = RECORDING_STATE.with_suffix(".tmp")
    try:
        tmp.write_text(json.dumps({
            "active": bool(active),
            "phase": phase,
            "started": started,
            "limit_sec": limit_sec,
            "hint": hint,
            "note": note,
            "level": level,
            "fake": bool(fake),
            "quit": quit_overlay,
            "expires_at": (time.time() + ttl) if (active and ttl) else None,
        }, ensure_ascii=False), encoding="utf-8")
    except OSError:
        return
    _replace_state(tmp)


# Сколько раз повторить подмену файла состояния, прежде чем сдаться.
STATE_REPLACE_TRIES = 6


def _replace_state(tmp):
    """
    Подменить файл состояния, пережив читателя.

    На Windows `os.replace` падает с отказом в доступе, если файл в этот момент
    ОТКРЫТ кем-то ещё, — а индикатор открывает его тридцать раз в секунду. Раньше
    ошибка молча проглатывалась, и запись пропадала. Для обновления уровня
    громкости это незаметно (через 0.1 с придёт следующее), но потерянной может
    оказаться и ЕДИНСТВЕННАЯ важная запись — та, что гасит капсулу в конце.
    Тогда индикатор висит над закрытым микрофоном до истечения срока годности.

    Замечено как редкий провал автотеста: капсула осталась поднятой после того,
    как микрофон закрылся, при том что двадцать прогонов подряд проходили чисто.
    Воспроизвести гонку намеренно не удалось — читатель в два потока, вшестеро
    чаще настоящего, не вызвал ни одного отказа. Поэтому здесь не «исправление
    доказанной причины», а защита от целого класса: единственная запись, потеря
    которой видна человеку, не должна зависеть от того, кто в этот момент открыл
    файл — индикатор, индексатор Windows или антивирус. Сдавшись, пишем в лог:
    молчаливый отказ и был тем, что мешало разобраться.
    """
    for attempt in range(STATE_REPLACE_TRIES):
        try:
            os.replace(tmp, RECORDING_STATE)
            return
        except PermissionError:
            time.sleep(0.01 * (attempt + 1))  # читатель вот-вот закроет файл
        except OSError:
            return  # диск/права — повтор не поможет, а ронять запись нельзя
    log("[warn] состояние индикатора не удалось записать: файл занят")


def clear_recording_state():
    """Гасит индикатор. Вызывается и при штатном выходе демона, и из atexit."""
    set_recording_state(False)


def recording_state_active():
    """
    Занята ли капсула прямо сейчас кем-то другим.

    Нужно ровно для одного решения: брать ли `Recorder`у индикатор в собственность.
    Демон поднимает капсулу ещё до создания рекордера (человек нажал — отклик обязан
    быть немедленным, до раскрутки микрофона), и перебивать его записями десять раз
    в секунду не надо. А `/voice` и `ask.py` капсулу не поднимают вовсе — там хозяин
    сам `Recorder`.

    Протухшее состояние считается свободным: писателя, который его оставил, уже нет.
    """
    try:
        state = json.loads(RECORDING_STATE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    if not state.get("active"):
        return False
    expires = state.get("expires_at")
    if expires is None:
        return True  # файл от старой версии: считаем занятым, чужое не перебиваем
    return time.time() <= float(expires)


def level_from_rms(rms):
    """
    Громкость в шкалу 0..1 для столбиков индикатора.

    По децибелам, а не линейно: слух логарифмичен, и на линейной шкале обычная речь
    (RMS около 0.05) даёт едва заметный столбик, а вся видимая часть достаётся крику.
    """
    if rms <= 1e-6:
        return 0.0
    db = 20 * math.log10(rms)
    return max(0.0, min(1.0, (db + 55) / 45))  # -55 дБ — тишина, -10 дБ — максимум


