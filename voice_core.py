# Полоса разборчивости. Основной тон голоса лежит ниже (85-250 Гц), но различаются
# звуки речи ФОРМАНТАМИ — резонансами голосового тракта в 300-3400 Гц. Это не
# теория, а измеренная причина инцидента 07.08: у записи из соседней комнаты
# 86% энергии сидело в 100-300 Гц, то есть до микрофона дошёл гул голоса без
# единого признака, по которому различаются слова. Считать такую запись «тихой,
# но пригодной» по общему RMS — ровно та ошибка, из-за которой мусор уехал в облако.
SPEECH_BAND_HZ = (300.0, 3400.0)
SPEECH_BLOCK = 480  # 30 мс при 16 кГц

# Ориентир «так звучит речь» — НЕ порог вердикта. Отсюда считаются две
# вспомогательные вещи: доля речевых блоков в логе и нижняя граница обрезки
# тишины. Вердикт «речи нет» строится на безразмерных признаках ниже.
#
# ⚠ Это число когда-то и было порогом вердикта — сначала 0.002, потом 0.008,
# потом 0.004, — и каждый раз оказывалось, что оно верно ровно для того
# микрофона, на котором его мерили. Полная история и данные обоих замеров лежат
# в шапке безразмерных признаков ниже; коротко: абсолютный уровень речи зависит
# от чувствительности устройства, поэтому порогом быть не может ни при каком
# значении. Не возвращайте его в вердикт.
SPEECH_REFERENCE_LEVEL = 0.004


def band_block_rms(audio, sr=SAMPLE_RATE):
    """Поблочный (30 мс) уровень сигнала внутри формантной полосы."""
    if audio is None or len(audio) < SPEECH_BLOCK:
        return np.zeros(0)
    n = len(audio) // SPEECH_BLOCK * SPEECH_BLOCK
    blocks = np.asarray(audio[:n], dtype=np.float64).reshape(-1, SPEECH_BLOCK)
    spec = np.abs(np.fft.rfft(blocks * np.hanning(SPEECH_BLOCK), axis=1))
    freqs = np.fft.rfftfreq(SPEECH_BLOCK, 1 / sr)
    band = (freqs >= SPEECH_BAND_HZ[0]) & (freqs <= SPEECH_BAND_HZ[1])
    # Парсеваль: нормируем на длину окна, чтобы число читалось как RMS в полосе
    return np.sqrt((spec[:, band] ** 2).sum(axis=1)) / SPEECH_BLOCK


# --------------------------------------------------------------------------- #
# Безразмерные признаки записи: одинаковы для любого микрофона
# --------------------------------------------------------------------------- #
# ЗАМЕР 1, 07.08, гарнитура (одна машина, один вечер). Вердикт каждой записи
# прочитан в расшифровке, а не выведен из уровня:
#
#   23:08:47   уровень речи 0.0687   нормальный текст
#   23:29:33                 0.0255   нормальный текст, самая тихая из удачных
#   23:32:54                 0.0026   «Я уже говорила с этой пиксией…» — ВЫДУМАНО
#   23:31:47                 0.0024   «Добрый день, я хочу…» — ВЫДУМАНО
#   23:11:29                 0.0000   «Добро пожаловать в Казахстан!» (98% нулей)
#
# ЗАМЕР 2, 11.08, тихий встроенный микрофон, 31 диктовка, ВСЕ расшифрованы верно:
#
#   уровень речи 0.0020-0.0089 — то есть самая тихая УДАЧНАЯ запись здесь тише,
#   чем ВЫДУМАННЫЙ текст из замера 1 (0.0026).
#
# Отсюда вывод, стоивший двух подходов: абсолютного порога не существует. Пока
# вердикт ставился по уровню, порог 0.008 помечал на этом микрофоне каждую
# диктовку (25 подряд, все ложные), 0.004 — каждую четвёртую. Пометка, которая
# стоит всегда, не значит ничего и не сработает в тот единственный раз, ради
# которого сделана.
#
# Ниже — отношения вместо уровней. Замер 11.08 по тем же 31 живой диктовке
# (−44…−25 dBFS) против четырёх заведомо провальных случаев:
#
#                              контраст   форманты   нули
#   живые диктовки              5.4-897   0.13-0.97  0.02-0.19
#   ─────────────────────────  каждый признак ловит СВОЙ вид отказа ↓
#   микрофон не слышит (шум)        1.2       0.38       0.00
#   далёкий гул без формант       15.8       0.00       0.00
#   Bluetooth не поднялся          3.5       0.39       0.99
#
# Отношения одинаковы, сколько бы ни выдавал микрофон, — в этом и смысл.
#
# Каждый признак ловит свой вид отказа, поэтому проверяются все три:
#   контраст   у речи есть слоги и паузы, у шума — нет;
#   форманты   голос из-за стены приходит гулом, в полосе разборчивости пусто;
#   нули       профиль Bluetooth не поднялся — в файле ровные нули.
MIN_MODULATION_CONTRAST = 2.5  # живые ≥5.4, шум 1.2
MIN_FORMANT_SHARE = 0.06       # живые ≥0.13, гул 0.00
MAX_ZERO_SHARE = 0.6           # живые ≤0.19, оборванный поток 0.99

# Выше этого контраст не считаем: если в паузах цифровой ноль, отношение упирается
# в защиту от деления на ноль (1e-12), а не в свойство звука. На живых записях
# 11.08 так и вышло — 4·10⁷ в строке лога и разъехавшаяся колонка diag_audio.py.
#
# Число выбрано по РЕАЛЬНОМУ диапазону, а не «с запасом от минимума»: на тихом
# встроенном микрофоне обычные диктовки дают 700-70000, потому что в паузах он
# отдаёт ровные нули. Потолок 1000 показывал бы «1000» четырём записям из шести,
# то есть колонка перестала бы различать что-либо в рабочем диапазоне. Вердикта
# потолок не касается ни при каком значении — порог стоит СНИЗУ (2.5).
MAX_MODULATION_CONTRAST = 10000.0


def modulation_contrast(audio, sr=SAMPLE_RATE):
    """
    Во сколько раз звучные моменты громче тихих — в полосе разборчивости.

    У речи всегда есть слоги и паузы, поэтому громкие блоки на порядок выше
    тихих. У микрофона, который просто шумит, уровень ровный, и отношение
    прижимается к единице. Величина безразмерная: она не меняется, если весь
    сигнал тише или громче.
    """
    brms = band_block_rms(audio, sr)
    if len(brms) < 10:
        return 0.0
    floor = float(np.percentile(brms, 10))
    return min(float(np.percentile(brms, 90) / (floor + 1e-12)),
               MAX_MODULATION_CONTRAST)


def formant_share(audio, sr=SAMPLE_RATE, block=1024):
    """
    Какая доля энергии громких моментов лежит в полосе разборчивости.

    Отвечает на вопрос, который не задаёт громкость: голос из соседней комнаты
    доходит гулом — энергии много, а формант, по которым речь и распознаётся, в
    ней нет. Считаем по громким блокам: в паузах доли считать нечего.
    """
    if audio is None or len(audio) < block * 4:
        return 0.0
    n = len(audio) // block * block
    blocks = np.asarray(audio[:n], dtype=np.float64).reshape(-1, block)
    spec = np.abs(np.fft.rfft(blocks * np.hanning(block), axis=1)) ** 2
    energy = spec.sum(axis=1)
    loud = spec[energy >= np.percentile(energy, 80)].mean(axis=0)
    freqs = np.fft.rfftfreq(block, 1 / sr)
    band = (freqs >= SPEECH_BAND_HZ[0]) & (freqs < SPEECH_BAND_HZ[1])
    return float(loud[band].sum() / (loud.sum() + 1e-30))


def zero_share(audio):
    """
    Доля почти-нулевых отсчётов — признак оборванного потока, а не тишины.

    Живой микрофон всегда шумит: даже в тихой комнате нулей единицы процентов.
    Ровные нули означают, что звук не дошёл вовсе — так выглядит Bluetooth,
    у которого не поднялся профиль микрофона (замер 07.08: 98% нулей).
    """
    if audio is None or len(audio) == 0:
        return 1.0
    return float(np.mean(np.abs(np.asarray(audio)) < 1e-4))


def speech_score(audio, sr=SAMPLE_RATE):
    """
    «Насколько громко в записи звучит РЕЧЬ» — 90-й перцентиль поблочного уровня
    в формантной полосе.

    Перцентиль, а не среднее: в диктовке всегда есть паузы, и среднее по ним
    размывает разницу между «человек говорил» и «микрофон шумел». 90-й перцентиль
    отвечает на нужный вопрос — насколько громки самые звучные моменты.

    Возвращает (скор, доля речевых блоков). Второе число не для порога, а для лога:
    по нему видно, была речь короткой или её не было вовсе.
    """
    brms = band_block_rms(audio, sr)
    if len(brms) == 0:
        return 0.0, 0.0
    return float(np.percentile(brms, 90)), float(np.mean(brms > SPEECH_REFERENCE_LEVEL))


def trim_silence(audio, sr=SAMPLE_RATE, pad_sec=0.3):
    """
    Срезать тишину по краям записи, оставив запас в `pad_sec`.

    Нужно в двух местах и по разным причинам. Для сравнения источников — чтобы
    входы были приведены к одному виду (иначе выигрывает тот, кого уже подрезали).
    Для отправки в облако — потому что Whisper на длинной тишине по краям
    склонен дописывать титры-приветствия: чем больше пустоты, тем охотнее.

    Порог относительный (доля от самого громкого места), а не абсолютный: тихий
    голос вблизи и громкий издалека должны обрезаться по своим краям, а не по
    общему для всех уровню.
    """
    brms = band_block_rms(audio, sr)
    if len(brms) == 0:
        return audio
    loud = brms > max(SPEECH_REFERENCE_LEVEL * 0.5, float(np.percentile(brms, 90)) * 0.12)
    idx = np.flatnonzero(loud)
    if len(idx) == 0:
        return audio  # резать нечего: речи не нашлось нигде — пусть решает вызывающий
    pad = int(pad_sec * sr / SPEECH_BLOCK)
    lo = max(0, idx[0] - pad) * SPEECH_BLOCK
    hi = min(len(brms), idx[-1] + 1 + pad) * SPEECH_BLOCK
    return np.asarray(audio[lo:hi])


def alarm_score(cfg):
    """
    Необязательный порог по АБСОЛЮТНОМУ уровню речи. По умолчанию выключен.

    Вердикт «в записи нет речи» ставится теперь по безразмерным признакам (см.
    MIN_MODULATION_CONTRAST и рядом) — они не зависят от чувствительности
    микрофона, тогда как абсолютный уровень зависит целиком. Этот ключ остаётся
    для того, кто хочет строже на СВОЁМ железе: посмотреть свои числа в
    `diag_audio.py` и поставить порог ниже самой тихой из своих удачных записей.

    Ноль (умолчание) — порог не применяется, работают только безразмерные
    признаки.
    """
    try:
        return max(0.0, float(cfg.get("speech_alarm_score", 0)))
    except (TypeError, ValueError):
        return 0.0


def audio_report(audio, sr=SAMPLE_RATE, alarm=0.0):
    """
    Метрики записи одной строкой — то, чего не хватало в логе 07.08.

    `quiet` — вердикт «речи в записи нет». Он складывается из трёх безразмерных
    признаков; `alarm` добавляет к ним необязательный порог по абсолютному уровню
    (по умолчанию выключен, см. alarm_score).
    """
    if audio is None or len(audio) == 0:
        return {"sec": 0.0, "rms": 0.0, "dbfs": -999.0, "peak": 0.0,
                "score": 0.0, "voiced": 0.0, "contrast": 0.0, "formants": 0.0,
                "zeros": 1.0, "quiet": True}
    a = np.asarray(audio, dtype=np.float64)
    rms = float(np.sqrt(np.mean(a * a)))
    score, voiced = speech_score(a, sr)
    contrast = modulation_contrast(a, sr)
    formants = formant_share(a, sr)
    zeros = zero_share(a)
    return {
        "sec": len(a) / sr,
        "rms": rms,
        "dbfs": 20 * np.log10(rms + 1e-12),
        "peak": float(np.max(np.abs(a))),
        "score": score,
        "voiced": voiced,
        "contrast": contrast,
        "formants": formants,
        "zeros": zeros,
        "quiet": (zeros > MAX_ZERO_SHARE
                  or contrast < MIN_MODULATION_CONTRAST
                  or formants < MIN_FORMANT_SHARE
                  or (alarm > 0 and score < alarm)),
    }


def quiet_reason(rep, alarm=0.0):
    """
    Какой именно признак забраковал запись — словами.

    Без этого пометка не подлежит разбору: «речи нет» одинаково выглядит и когда
    микрофон отдал нули, и когда голос дошёл гулом из-за стены, а лечится это
    по-разному — первое проверкой устройства, второе тем, чтобы говорить в него.
    """
    if rep.get("zeros", 0) > MAX_ZERO_SHARE:
        return (f"поток оборван: {rep['zeros'] * 100:.0f}% отсчётов — нули, "
                f"похоже, микрофон не отдал звук")
    if rep.get("contrast", 0) < MIN_MODULATION_CONTRAST:
        return (f"ровный шум без слогов и паузы: контраст {rep['contrast']:.1f} "
                f"при минимуме {MIN_MODULATION_CONTRAST}")
    if rep.get("formants", 0) < MIN_FORMANT_SHARE:
        return (f"в полосе разборчивости почти ничего: форманты "
                f"{rep['formants']:.2f} при минимуме {MIN_FORMANT_SHARE} — "
                f"голос дошёл гулом")
    if alarm > 0 and rep.get("score", 0) < alarm:
        return f"уровень речи {rep['score']:.5f} ниже вашего порога {alarm}"
    return "признаки речи не найдены"


def format_audio_report(rep):
    # Контраст и форманты в строке обязательны: по ним теперь ставится вердикт, и
    # разбор жалобы «почему пометило» без них снова уперся бы в спектр WAV.
    return (f"{rep['sec']:.1f} с, речь={rep['score']:.5f} "
            f"({rep['voiced'] * 100:.0f}% блоков), уровень={rep['dbfs']:.0f} dBFS, "
            f"пик={rep['peak']:.3f}, контраст={rep.get('contrast', 0):.1f}, "
            f"форманты={rep.get('formants', 0):.2f}")


