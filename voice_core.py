# позвать индикатор, а потому что звать было нечего, функция жила в другом файле.
# Здесь она доступна всем трём обёрткам, и `Recorder` поднимает капсулу сам —
# от факта открытия потока, а не от того, вспомнил ли об этом вызывающий код.

# Сколько состояние остаётся действительным без обновления.
#
# Сроков два, потому что фазы обновляются по-разному. «Расшифровываю» и «привожу
# в порядок» пишутся ОДИН раз и держатся весь сетевой шаг — им нужен запас на самый
# медленный ответ Groq. Фаза записи переписывается десять раз в секунду, и такой
# запас ей не просто не нужен, а вреден: если писателя убьют на середине записи
# (диспетчер задач, падение), капсула «идёт запись» провисит над давно закрытым
# микрофоном все две минуты. То есть соврёт ровно в ту сторону, от которой этот
# индикатор и заведён.
#
# 10 секунд — с запасом больше самого долгого открытия потока (перебор кандидатов
# по 0.8 с прогрева каждый), но настолько же меньше, насколько заметна ложь.
STATE_TTL_SEC = 120.0
REC_TTL_SEC = 10.0
FLASH_TTL_EXTRA = 0.6

